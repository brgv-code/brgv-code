import { escapeXml } from './text.mjs';

function picture({ file, alt, href, widthPercent, version }) {
  const path = `./profile/${file}`;
  return `<a href="${escapeXml(href)}"><picture><source media="(prefers-color-scheme: dark)" srcset="${path}-dark.svg?v=${version}"><img src="${path}-light.svg?v=${version}" width="${widthPercent}%" alt="${escapeXml(alt)}"></picture></a>`;
}

/** Panels in one row share a paragraph; rows are separate paragraphs so GitHub spaces them. */
export function renderReadme(rows) {
  const paragraphs = rows.map((row) => {
    const widthPercent = 100 / row.length;
    return row.map((panel) => picture({ ...panel, widthPercent })).join('');
  });
  return `<!-- Generated by scripts/build.mjs. Edit profile.config.json, not this file. -->\n\n${paragraphs.join('\n\n')}\n`;
}
